import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const docsSiteRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(docsSiteRoot, "..", "..");
const algoDir = path.join(repoRoot, "backend/src/algo");
const outputPath = path.resolve(
  docsSiteRoot,
  "src/content/docs/platform/algos.md",
);

function parseLeadJsdoc(src) {
  const m = src.match(/\/\*\*\s*([\s\S]*?)\s*\*\//);
  if (!m) return { title: "", summary: "" };
  const lines = m[1]
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trimEnd())
    .filter((l) => l.trim().length > 0);
  if (lines.length === 0) return { title: "", summary: "" };
  const title = lines[0];
  const body = lines.slice(1).join(" ");
  const idx = body.search(/\.\s+[A-Z]/);
  const summary = idx > 0 ? `${body.slice(0, idx + 1).trim()}` : body;
  return { title, summary };
}

const files = fs
  .readdirSync(algoDir)
  .filter((f) => f.endsWith("-strategy.ts"))
  .sort();

const rows = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(algoDir, f), "utf8");
  const { title, summary } = parseLeadJsdoc(src);
  const slug = f.replace("-strategy.ts", "");
  rows.push({ slug, file: f, title, summary });
}

const lines = [
  "---",
  "title: Algo Strategies",
  "description: The execution algorithms shipped by the platform.",
  "---",
  "",
  "<!-- This page is generated by docs/site/scripts/generate-algos.mjs from the leading JSDoc of each backend/src/algo/*-strategy.ts file. Edits will be lost — change the algo source instead. -->",
  "",
  "| Strategy | Description |",
  "|----------|-------------|",
];
for (const r of rows) {
  lines.push(`| **${r.title || r.slug}** | ${r.summary || "—"} |`);
}

const body = `${lines.join("\n")}\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, body);

console.log(
  `Generated ${path.relative(repoRoot, outputPath)} (${rows.length} algos)`,
);
