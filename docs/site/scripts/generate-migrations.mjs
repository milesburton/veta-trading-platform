import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const docsSiteRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(docsSiteRoot, "..", "..");
const migrationsDir = path.join(repoRoot, "backend/db/migrations");
const outputPath = path.resolve(
  docsSiteRoot,
  "src/content/docs/reference/migrations.md",
);

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => /^\d{4}_.+\.sql$/.test(f))
  .sort();

if (files.length === 0) {
  throw new Error("No migrations found");
}

const first = files[0].slice(0, 4);
const last = files[files.length - 1].slice(0, 4);
const range = first === last ? first : `${first}–${last}`;

const lines = [
  "---",
  "title: Database Migrations",
  "description: Numbered Postgres schema migrations applied in order at startup.",
  "---",
  "",
  "<!-- This page is generated by docs/site/scripts/generate-migrations.mjs from backend/db/migrations/. Edits will be lost — add a new migration file instead. -->",
  "",
  `Range: \`${range}\` · Count: \`${files.length}\``,
  "",
  "| File | Title |",
  "|------|-------|",
];
for (const f of files) {
  const num = f.slice(0, 4);
  const title = f
    .replace(/^\d{4}_/, "")
    .replace(/\.sql$/, "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
  lines.push(`| \`${num}\` | ${title} |`);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${lines.join("\n")}\n`);

console.log(
  `Generated ${path.relative(repoRoot, outputPath)} (${files.length} migrations, ${range})`,
);
