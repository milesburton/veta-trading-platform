export interface SentimentResult {
  sentiment: "positive" | "negative" | "neutral";
  score: number;
}

/**
 * Scores free text against the Loughran-McDonald financial sentiment
 * lexicon: net (positive word count − negative word count), with the sign
 * of the net score determining the label. A tied score (including no
 * lexicon words matched at all) is neutral.
 */
export function scoreSentiment(text: string): SentimentResult {
  const words = text.toLowerCase().match(/\b[a-z][a-z-]*[a-z]\b|\b[a-z]{2,}\b/g) ?? [];
  let score = 0;
  for (const w of words) {
    if (LM_POSITIVE.has(w)) score++;
    else if (LM_NEGATIVE.has(w)) score--;
  }
  const sentiment = score > 0 ? "positive" : score < 0 ? "negative" : "neutral";
  return { sentiment, score };
}

/**
 * Extracts probable stock ticker mentions: 2-5 letter uppercase runs,
 * filtered against a stopword set of common financial acronyms that
 * would otherwise false-positive as tickers (CEO, GDP, Q1, ...), deduped,
 * capped at 5 results. Lowercase text never matches — this is
 * deliberately case-sensitive.
 */
export function extractTickers(text: string): string[] {
  const matches = text.match(/\b[A-Z]{2,5}\b/g) ?? [];
  return [...new Set(matches.filter((m) => !IGNORE_TICKERS.has(m)))].slice(0, 5);
}

/** Slugifies a label into a lowercase, hyphen-separated identifier. Symbol-only input produces an empty string — callers should provide a fallback. */
export function slugify(label: string): string {
  return label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
